#!/usr/bin/env python3
"""Writes jamovi/distRidge.{a,r,u}.yaml (the "Ridgeline (green-blue-red)" analysis) from distNum.a.yaml.
Run from the repository root AFTER editing distNum.a.yaml:  python3 tools/gen_ridge_yaml.py"""
import re, sys
sys.path.insert(0, "tools")
from ui_gen import *
ROOT = "jamovi/"
KEEP = ["data", "vars", "orientation", "sortVars", "useDesc", "transform", "invertVars", "reversePalette", "plotTheme",
        "textSize", "alpha", "lineWidth", "valueLabel", "title", "showN", "ridgeOverlap", "ridgeAdjust", "ridgeTrim", "ridgeMedian"]
src = open(ROOT + "distNum.a.yaml").read()
def block(name):
    m = re.search(r"  - name: %s\n(?:    [^\n]*\n|      [^\n]*\n)*" % re.escape(name), src)
    assert m, name
    return m.group(0)
head = """---
# Ridgeline, green-blue-red (distRidge): OPTIONS. Generated by tools/gen_ridge_yaml.py from distNum.a.yaml; edit there.
# The ridgeline plot of Compare Numeric as its own analysis; the ridges are coloured green, blue, red from top to bottom.
name: distRidge
title: Ridgeline (green-blue-red)
category: plots
menuGroup: comparePlots
version: '1.0.0'
jas: '1.2'
options:
"""
body = "".join(block(n) for n in KEEP).replace("title: Invert palette", "title: Reverse the colours")
open(ROOT + "distRidge.a.yaml", "w").write(head + body + "...\n")

clear = "".join(f"      - {n}\n" for n in KEEP if n not in ("data",))
open(ROOT + "distRidge.r.yaml", "w").write(f"""---
# Ridgeline, green-blue-red (distRidge): RESULTS. One image, always shown.
name: distRidge
title: Ridgeline (green-blue-red)
jrs: '1.1'
refs:
  - comparePlots
  - ggplot2
items:
  - name: hint
    title: ''
    type: Html
    visible: false
  - name: plot_ridge
    title: Ridgeline (density) plot
    type: Image
    width: 450
    height: 400
    renderFun: .plot_ridge
    requiresData: true
    clearWith:
{clear}""")

s = head_ui("Ridgeline (green-blue-red)", "distRidge")
s += appearance_groups([
    ("<b>Variables</b>", [D("orientation"), D("sortVars"), D("transform"), C("invertVars"), C("useDesc"), S("valueLabel")]),
    ("<b>Appearance</b>", [C("reversePalette"), D("plotTheme"), T("alpha", suffix="%"), T("lineWidth")]),
    ("<b>Ridgeline</b>", [T("ridgeOverlap", suffix="%"), T("ridgeAdjust"), C("ridgeTrim"), C("ridgeMedian")]),
    ("<b>Text and labels</b>", [T("textSize"), S("title"), C("showN")])])
open(ROOT + "distRidge.u.yaml", "w").write(s)
print("ridge yaml written")
